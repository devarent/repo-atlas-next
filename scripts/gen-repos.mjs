import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";

const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, "$1"));
const root = path.resolve(here, "..");
const source = path.resolve(root, "..", "repo-atlas", "atlas-data.js");

const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(source, "utf8"), sandbox);

const tracks = sandbox.window.ATLAS_TRACKS;
const repos = sandbox.window.ATLAS_REPOS;

const q = (v) => JSON.stringify(v ?? null);
const out = `// GENERATED by scripts/gen-repos.mjs — jangan edit manual.
export type Track = {
  key: string; flag: string; country: string; word: string;
  theme: string; color: string; note: string;
};
export type AtlasRepo = {
  r: string; c: string; t: string; l: string; y: string;
  k: string[]; d: string; p: string | null;
};

export const tracks: Track[] = ${JSON.stringify(tracks, null, 2)};

export const repos: AtlasRepo[] = ${JSON.stringify(repos, null, 2)};

export const trackByKey: Record<string, Track> = Object.fromEntries(
  tracks.map((t) => [t.key, t]),
);
`;

fs.mkdirSync(path.join(root, "lib", "data"), { recursive: true });
fs.writeFileSync(path.join(root, "lib", "data", "repos.ts"), out, "utf8");
console.log(`repos.ts: ${repos.length} repos, ${tracks.length} tracks`);
